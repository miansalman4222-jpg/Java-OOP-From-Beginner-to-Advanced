public class Main {
    public static void main(String[] args) {
        // Print numbers from 1 to 5
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

        // Print even numbers from 2 to 10
        int number = 2;
        while (number <= 10) {
            System.out.println("Even: " + number);
            number += 2;
        }
    }
}
